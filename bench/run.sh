#!/usr/bin/env bash
# Benchmarks v12n against Ontop on the same PostgreSQL, mapping and
# queries (bench/README.md). Brings up PostgreSQL and Ontop under the
# Compose project `v12n-bench`, loads the scaled MDR data, runs
# bench/bench.py, and removes everything (`down -v`) on exit.
#
#   bench/run.sh                         100k alerts
#   BENCH_ALERTS=1000000 bench/run.sh    1M alerts
#
# Environment:
#   BENCH_ALERTS           alerts to generate (default 100000)
#   BENCH_RUNS             timed runs per query and engine (default 20)
#   BENCH_WARMUP           warm-up runs per query and engine (default 3)
#   BENCH_CLI_RUNS         timed `v12n query` runs per query (default 10)
#   BENCH_STARTS           start-ups measured per engine (default 3)
#   BENCH_LOAD_CLIENTS     concurrent clients in the load phase (default 8)
#   BENCH_LOAD_SECONDS     length of the load phase (default 15)
#   BENCH_ONTOP_JAVA_ARGS  Ontop JVM flags (default -Xmx256m, as testenv/difftest.sh)
#   BENCH_OUT              output directory (default bench/results/<alerts>-<UTC time>)
#   BENCH_PG_PORT, BENCH_ONTOP_PORT, BENCH_V12N_PORT
#                          localhost ports (55434, 58090, 57890; Ontop also
#                          uses the next one, v12n the next two)
#
# Needs Docker with Compose v2, python3, a Rust toolchain, and
# testenv/jdbc/ (testenv/fetch-jdbc.sh). Development credentials only;
# every port is bound to localhost.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
alerts="${BENCH_ALERTS:-100000}"
out="${BENCH_OUT:-$root/bench/results/$alerts-$(date -u +%Y%m%dT%H%M%SZ)}"
project="v12n-bench"
compose_file="$out/compose.yml"
pg_port="${BENCH_PG_PORT:-55434}"
ontop_port="${BENCH_ONTOP_PORT:-58090}"
v12n_port="${BENCH_V12N_PORT:-57890}"
java_args="${BENCH_ONTOP_JAVA_ARGS:--Xmx256m}"
# The images of testenv/difftest.sh, pinned by digest.
postgres_image="postgres:17.11@sha256:b8faeff7712663c2773a190181e1246e37e364b887611c04658c28b44e2408fe"
ontop_image="ontop/ontop:5.5.0@sha256:d19a2055b02812c8ecc0a00cca1733c1669c4143dfeb728acbfdff92b45e94d7"
# Read-only login per engine, so pg_stat_statements tells their statements apart.
roles="bench_v12n bench_v12n_limit bench_ontop bench_ontop_host"

compose() { docker compose -p "$project" -f "$compose_file" "$@"; }
log() { printf '[bench %4ss] %s\n' "$SECONDS" "$*" >&2; }
psql_admin() { compose exec -T postgres psql -X -q -v ON_ERROR_STOP=1 -U v12n -d mdr "$@"; }

generate() {
  cat >"$compose_file" <<EOF
# Generated by bench/run.sh. Development credentials only.
name: $project
services:
  postgres:
    image: $postgres_image
    command: ["postgres", "-c", "shared_preload_libraries=pg_stat_statements", "-c", "pg_stat_statements.track_planning=on"]
    environment: { POSTGRES_USER: v12n, POSTGRES_PASSWORD: v12n-dev, POSTGRES_DB: mdr }
    ports: ["127.0.0.1:$pg_port:5432"]
    extra_hosts: ["host.docker.internal:host-gateway"]
    healthcheck:
      test: ["CMD", "pg_isready", "-h", "127.0.0.1", "-U", "v12n", "-d", "mdr"]
      interval: 1s
      timeout: 5s
      retries: 60
  ontop:
    image: $ontop_image
    depends_on: { postgres: { condition: service_healthy } }
    environment:
      ONTOP_MAPPING_FILE: /bench/mapping.ttl
      ONTOP_DB_URL: jdbc:postgresql://postgres:5432/mdr
      ONTOP_DB_USER: bench_ontop
      ONTOP_DB_PASSWORD: bench-dev
      ONTOP_DB_DRIVER: org.postgresql.Driver
      ONTOP_JAVA_ARGS: "$java_args"
    # bench.py polls the endpoint itself; a health probe would add queries.
    healthcheck: { disable: true }
    ports: ["127.0.0.1:$ontop_port:8080"]
    volumes:
      - "$root/bench/mdr/mapping.ttl:/bench/mapping.ttl:ro"
      - "$root/testenv/jdbc:/opt/ontop/jdbc:ro"
  # The same Ontop reaching PostgreSQL through its published port, as the
  # native v12n does: on Docker Desktop that path crosses the VM boundary.
  ontop-host:
    image: $ontop_image
    depends_on: { postgres: { condition: service_healthy } }
    environment:
      ONTOP_MAPPING_FILE: /bench/mapping.ttl
      ONTOP_DB_URL: "jdbc:postgresql://host.docker.internal:$pg_port/mdr"
      ONTOP_DB_USER: bench_ontop_host
      ONTOP_DB_PASSWORD: bench-dev
      ONTOP_DB_DRIVER: org.postgresql.Driver
      ONTOP_JAVA_ARGS: "$java_args"
    healthcheck: { disable: true }
    extra_hosts: ["host.docker.internal:host-gateway"]
    ports: ["127.0.0.1:$((ontop_port + 1)):8080"]
    volumes:
      - "$root/bench/mdr/mapping.ttl:/bench/mapping.ttl:ro"
      - "$root/testenv/jdbc:/opt/ontop/jdbc:ro"
EOF
}

cleanup() {
  local status=$?
  log "removing the stack"
  compose down -v --remove-orphans >/dev/null 2>&1 || true
  exit "$status"
}

if ! ls "$root"/testenv/jdbc/postgresql-*.jar >/dev/null 2>&1; then
  echo "no JDBC driver in testenv/jdbc/: run testenv/fetch-jdbc.sh first" >&2
  exit 1
fi
mkdir -p "$out"
generate
trap cleanup EXIT

log "building v12n (release)"
cargo build --release --locked -p v12n-cli
log "translation without a database"
cargo bench --locked -p v12n-server --bench translate -- --json >"$out/translate.jsonl"

compose down -v --remove-orphans >/dev/null 2>&1 || true
compose up -d --wait postgres
log "postgres ready; loading $alerts alerts"
psql_admin -c "CREATE EXTENSION pg_stat_statements"
psql_admin <"$root/bench/mdr/schema.sql"
psql_admin -v alerts="$alerts" <"$root/bench/mdr/generate.sql"
for role in $roles; do
  psql_admin -c "CREATE ROLE $role LOGIN PASSWORD 'bench-dev'" \
    -c "GRANT SELECT ON ALL TABLES IN SCHEMA public TO $role"
done
log "data loaded"
# Created now, started by bench.py, so that its start-up time is the
# container start and not the image pull or the container creation.
compose create ontop ontop-host

settings="$(printf '{"alerts": %s, "runs": %s, "warmup": %s, "cli_runs": %s, "ontop_java_args": "%s", "v12n_commit": "%s", "v12n_statement_timeout": "0", "v12n_row_limit": "0 (and 10000 for v12n-row-limit)", "http": "POST, new connection per request"}' \
  "$alerts" "${BENCH_RUNS:-20}" "${BENCH_WARMUP:-3}" "${BENCH_CLI_RUNS:-10}" "$java_args" \
  "$(git -C "$root" rev-parse --short HEAD 2>/dev/null || echo unknown)")"

python3 "$root/bench/bench.py" \
  --out "$out" \
  --compose "docker compose -p $project -f $compose_file" \
  --v12n "$root/target/release/v12n" \
  --mapping "$root/bench/mdr/mapping.ttl" \
  --queries "$root/bench/queries" \
  --pg-port "$pg_port" \
  --ontop-port "$ontop_port" \
  --v12n-port "$v12n_port" \
  --runs "${BENCH_RUNS:-20}" \
  --warmup "${BENCH_WARMUP:-3}" \
  --cli-runs "${BENCH_CLI_RUNS:-10}" \
  --starts "${BENCH_STARTS:-3}" \
  --load-clients "${BENCH_LOAD_CLIENTS:-8}" \
  --load-seconds "${BENCH_LOAD_SECONDS:-15}" \
  --settings "$settings"

log "done: $out/results.md"
